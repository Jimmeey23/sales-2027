/* ─────────────────────────────────────────────────────────────────────────────
   The Bengaluru 2027 plan, as supplied by the studio.

   Kenkere House runs a campaign every month; Pop-up joins for four of them. Each
   row is transcribed exactly as given — list price, discount, offer price, bonus
   value, units and expected revenue — so the month plans, the offer bank and the
   coverage maths all read from one source of truth.

   Fields the source left blank (units or revenue on a few rows) are `null` rather
   than guessed: the UI shows them as unquantified instead of inventing a number.
   ──────────────────────────────────────────────────────────────────────────── */

export type Slot = 'newcomer' | 'lapsed' | 'renewal';

export interface PlanOffer {
  /** 1-indexed month. */
  month: number;
  studio: 'Kenkere House' | 'Pop-up';
  name: string;
  /** offer_type key understood by the offer card and the bank filters. */
  type: 'percentage' | 'fixed_price' | 'value_add' | 'bundle' | 'bogo_duo' | 'referral' | 'annual' | 'experience';
  /** objective key understood by the plan grouping. */
  objective:
    | 'acquisition'
    | 'trial_conversion'
    | 'referral'
    | 'retention'
    | 'annual_membership'
    | 'additional_purchase'
    | 'reactivation';
  slot: Slot | null;
  /** The campaign mechanic, in the source's own words ("Discount + value-add"). */
  mechanic: string;
  baseProduct: string;
  /** What the client gets, verbatim. */
  gets: string;
  audience: string;
  /** The window as written, plus resolvable dates where the source gives them. */
  window: string;
  start?: string;
  end?: string;
  listPrice?: number | null;
  discountPct?: number | null;
  fixedPrice?: number | null;
  offerPrice?: number | null;
  bonusValue?: number | null;
  totalValuePct?: number | null;
  units?: number | null;
  revenue?: number | null;
  why?: string;
}

