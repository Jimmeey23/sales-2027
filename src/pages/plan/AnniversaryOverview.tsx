/* The 9th Anniversary plan of action, read from src/data/anniversary2027.json. That file is
   generated by scripts/build-anniversary-plan.mjs: every target, funnel figure, price, buyer
   count and revenue line comes from the April months of the plan of record, so this page shows
   the same numbers as the April month plan and Target Metrics. */

// One decimal in lakh everywhere on this page, so the hero, the tables and the summary agree.
const lakh = (v: number) => `₹${(v / 100000).toLocaleString('en-IN', { minimumFractionDigits: 1, maximumFractionDigits: 1 })}L`;
const pct = (part: number, whole: number) => (whole > 0 ? `${Math.round((part / whole) * 100)}%` : '—');
const SLOT: Record<string, string> = {
  newcomer: 'Newcomer',
  referral: 'Referral',
  lapsed: 'Winback',
  renewal: 'Renewal',
  upgrade: 'Upgrade',
  spot: 'Flash',
};

function Section({
  id,
  icon,
  title,
  lede,
  children,
}: {
  id: string;
  icon: React.ReactNode;
  title: string;
  lede?: string;
  children: React.ReactNode;
}) {
  return (
    <section className="ao-section" id={`ao-${id}`}>
      <header className="ao-sec-head">
        <span className="ao-sec-icon">{icon}</span>
        <div>
          <h2>{title}</h2>
          {lede && <p>{lede}</p>}
        </div>
      </header>
      {children}
    </section>
  );
}

